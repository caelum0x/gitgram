import type { CheckpointRow } from "../store/repo.js";
import type { Manifest } from "../core/manifest.js";

/**
 * Generate a debugging prompt for a regression between two checkpoints
 */
export function generateDebugRegressionPrompt(
  fromCheckpoint: CheckpointRow,
  toCheckpoint: CheckpointRow,
  manifestFrom: Manifest,
  manifestTo: Manifest
): string {
  const filesFrom = new Map(manifestFrom.files.map(f => [f.path, f]));
  const filesTo = new Map(manifestTo.files.map(f => [f.path, f]));

  const added: string[] = [];
  const modified: string[] = [];
  const deleted: string[] = [];

  for (const [path, file] of filesTo) {
    if (!filesFrom.has(path)) {
      added.push(path);
    } else if (filesFrom.get(path)?.hash !== file.hash) {
      modified.push(path);
    }
  }

  for (const path of filesFrom.keys()) {
    if (!filesTo.has(path)) {
      deleted.push(path);
    }
  }

  return `# Debug Regression Analysis

## Context

A regression was introduced between these two checkpoints:

### Working State (Before)
- **Checkpoint**: ${fromCheckpoint.checkpointId}
- **Name**: ${fromCheckpoint.name}
- **Created**: ${fromCheckpoint.createdAt}

### Broken State (After)
- **Checkpoint**: ${toCheckpoint.checkpointId}
- **Name**: ${toCheckpoint.name}
- **Created**: ${toCheckpoint.createdAt}

## Changes

### Files Modified (${modified.length})
${modified.slice(0, 20).map(f => `- ${f}`).join('\n')}
${modified.length > 20 ? `\n... and ${modified.length - 20} more` : ''}

### Files Added (${added.length})
${added.slice(0, 10).map(f => `- ${f}`).join('\n')}
${added.length > 10 ? `\n... and ${added.length - 10} more` : ''}

### Files Deleted (${deleted.length})
${deleted.slice(0, 10).map(f => `- ${f}`).join('\n')}
${deleted.length > 10 ? `\n... and ${deleted.length - 10} more` : ''}

## Investigation Steps

1. **Review modified files** - Focus on the ${modified.length} files that changed
2. **Check added files** - New files might introduce bugs
3. **Verify deleted files** - Missing files could break dependencies
4. **Run tests** - Compare test results between the two states
5. **Check logs** - Look for error messages or warnings

## Suggested Debugging Approach

1. Start with the most critical modified files
2. Use \`tm_get_file_at\` to compare file contents between checkpoints
3. Look for patterns in the changes (e.g., all in a specific module)
4. Test hypotheses by restoring to intermediate checkpoints
5. Once found, create a fix and checkpoint it as "Fixed regression"

## Quick Commands

\`\`\`bash
# View file at working checkpoint
tm_get_file_at --checkpoint ${fromCheckpoint.checkpointId} --file <path>

# View file at broken checkpoint
tm_get_file_at --checkpoint ${toCheckpoint.checkpointId} --file <path>

# Restore to working state to verify
tm_checkpoint_restore --checkpoint ${fromCheckpoint.checkpointId}
\`\`\`
`;
}

/**
 * Generate an incident postmortem report
 */
export function generatePostmortem(
  fromCheckpoint: CheckpointRow,
  toCheckpoint: CheckpointRow,
  incidentDescription: string,
  resolution?: string
): string {
  return `# Incident Postmortem

## Incident Summary

${incidentDescription}

## Timeline

### Last Known Good State
- **Checkpoint**: ${fromCheckpoint.checkpointId}
- **Name**: ${fromCheckpoint.name}
- **Time**: ${fromCheckpoint.createdAt}
- **Status**: ✅ Working

### Incident Detected
- **Checkpoint**: ${toCheckpoint.checkpointId}
- **Name**: ${toCheckpoint.name}
- **Time**: ${toCheckpoint.createdAt}
- **Status**: ❌ Broken

**Duration**: ${calculateDuration(fromCheckpoint.createdAt, toCheckpoint.createdAt)}

## Root Cause Analysis

${resolution || '_To be filled after investigation_'}

## What Went Wrong

1. **Technical Details**: _Describe the technical issue_
2. **Detection**: How was the issue discovered?
3. **Impact**: What was affected?

## Resolution

${resolution || '_Pending investigation_'}

## Lessons Learned

### What Went Well
- AITimeMachine captured the exact working state
- We can restore to the last good checkpoint
- Complete history is preserved for analysis

### What Could Be Improved
- Earlier detection mechanisms
- Better testing before checkpointing
- More descriptive checkpoint names

## Action Items

- [ ] Review checkpoint naming conventions
- [ ] Add automated tests for this scenario
- [ ] Document the fix for future reference
- [ ] Update team practices if needed

## Recovery Process

1. Restored to checkpoint: ${fromCheckpoint.checkpointId}
2. Investigated changes using \`tm_diff_checkpoints\`
3. Applied fix
4. Created new checkpoint: "Fixed: ${incidentDescription.slice(0, 50)}"

---

Generated by AITimeMachine at ${new Date().toISOString()}
`;
}

