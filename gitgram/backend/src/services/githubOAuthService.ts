interface UpsertResult {
  dbUser: {
    id: string;
    email: string;
    username: string | null;
    displayName: string | null;
    avatar: string | null;
    githubUsername: string | null;
    bio: string | null;
  };
  isNewUser: boolean;
}

async function upsertUser(
  githubUser: GitHubUser,
  accessToken: string,
  email: string
): Promise<UpsertResult> {
  const githubIdStr = String(githubUser.id);

  // Case 1: user already linked by GitHub ID — refresh token + basic fields
  const byGitHubId = await prisma.user.findUnique({
    where: { githubId: githubIdStr },
    select: {
      id: true,
      email: true,
      username: true,
      displayName: true,
      avatar: true,
      githubUsername: true,
      bio: true,
    },
  });

  if (byGitHubId) {
    const updated = await prisma.user.update({
      where: { id: byGitHubId.id },
      data: {
        githubAccessToken: accessToken,
        githubUsername: githubUser.login,
        // Refresh avatar only if GitHub has one
        ...(githubUser.avatar_url ? { avatar: githubUser.avatar_url } : {}),
      },
      select: {
        id: true,
        email: true,
        username: true,
        displayName: true,
        avatar: true,
        githubUsername: true,
        bio: true,
      },
    });

    return { dbUser: updated, isNewUser: false };
  }

  // Case 2: existing user matched by email — link GitHub to their account
  const byEmail = await prisma.user.findUnique({
    where: { email },
    select: {
      id: true,
      email: true,
      username: true,
      displayName: true,
      avatar: true,
      githubUsername: true,
      bio: true,
    },
  });

  if (byEmail) {
    const linked = await prisma.user.update({
      where: { id: byEmail.id },
      data: {
        githubId: githubIdStr,
        githubUsername: githubUser.login,
        githubAccessToken: accessToken,
        avatar: byEmail.avatar ?? githubUser.avatar_url,
      },
      select: {
        id: true,
        email: true,
        username: true,
        displayName: true,
        avatar: true,
        githubUsername: true,
        bio: true,
      },
    });

    logger.info(`Linked GitHub account @${githubUser.login} to existing user ${byEmail.id}`);
    return { dbUser: linked, isNewUser: false };
  }

  // Case 3: brand new user — create user + account records
  const newUser = await prisma.user.create({
    data: {
      email,
      githubId: githubIdStr,
      githubUsername: githubUser.login,
      githubAccessToken: accessToken,
      username: githubUser.login,
      displayName: githubUser.name ?? githubUser.login,
      avatar: githubUser.avatar_url,
      bio: githubUser.bio ?? null,
      emailVerified: true, // GitHub-verified email
    },
    select: {
      id: true,
      email: true,
      username: true,
      displayName: true,
      avatar: true,
      githubUsername: true,
      bio: true,
    },
  });

  await prisma.account.create({
    data: {
      type: 'USER',
      username: githubUser.login,
      displayName: githubUser.name ?? githubUser.login,
      avatar: githubUser.avatar_url,
      userId: newUser.id,
    },
  });

  logger.info(`Created new Gitgram user ${newUser.id} from GitHub @${githubUser.login}`);
  return { dbUser: newUser, isNewUser: true };
}

function issueTokens(userId: string): AuthTokens {
  const accessToken = signAccessToken({ userId });
  const refreshToken = signRefreshToken({ userId });
  return { accessToken, refreshToken };
}
