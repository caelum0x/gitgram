/**
 * GitHub OAuth Service
 *
 * Comprehensive GitHub OAuth integration providing authorization URL generation,
 * token exchange, user data fetching, email resolution, profile refresh, and
 * the full callback flow with JWT issuance.
 *
 * Rate-limit aware: inspects X-RateLimit-* headers on every GitHub API call
 * and surfaces a structured error when the limit is exhausted.
 */

import axios, { AxiosResponse } from 'axios';
import jwt, { SignOptions } from 'jsonwebtoken';
import prisma from '../utils/prisma';
import logger from '../utils/logger';
import { config } from '../config/env';

// ---------------------------------------------------------------------------
// Domain types
// ---------------------------------------------------------------------------

export interface GitHubTokens {
  access_token: string;
  token_type: string;
  scope: string;
}

export interface GitHubUser {
  id: number;
  login: string;
  name: string | null;
  email: string | null;
  avatar_url: string;
  bio: string | null;
  company: string | null;
  location: string | null;
  blog: string | null;
  followers: number;
  following: number;
  public_repos: number;
}

export interface GitHubEmail {
  email: string;
  primary: boolean;
  verified: boolean;
  visibility: string | null;
}

export interface AuthTokens {
  accessToken: string;
  refreshToken: string;
}

export interface UserRecord {
  id: string;
  email: string;
  username: string | null;
  displayName: string | null;
  avatar: string | null;
  githubUsername: string | null;
  bio: string | null;
}

export interface CallbackResult {
  user: UserRecord;
  isNewUser: boolean;
  tokens: AuthTokens;
}

// ---------------------------------------------------------------------------
// Internal helpers
// ---------------------------------------------------------------------------

interface RateLimitInfo {
  limit: number;
  remaining: number;
  reset: number; // Unix timestamp
}

function extractRateLimit(response: AxiosResponse): RateLimitInfo {
  return {
    limit: parseInt(String(response.headers['x-ratelimit-limit'] ?? '60'), 10),
    remaining: parseInt(String(response.headers['x-ratelimit-remaining'] ?? '1'), 10),
    reset: parseInt(String(response.headers['x-ratelimit-reset'] ?? '0'), 10),
  };
}

function assertRateLimitNotExhausted(response: AxiosResponse, context: string): void {
  const rl = extractRateLimit(response);

  if (rl.remaining === 0) {
    const resetAt = new Date(rl.reset * 1000).toISOString();
    throw new Error(
      `GitHub API rate limit exhausted for "${context}". ` +
        `Limit: ${rl.limit}, resets at: ${resetAt}`
    );
  }

  if (rl.remaining < 5) {
    logger.warn(`GitHub API rate limit low for "${context}": ${rl.remaining} calls remaining`);
  }
}

function githubApiHeaders(accessToken: string): Record<string, string> {
  return {
    Authorization: `Bearer ${accessToken}`,
    Accept: 'application/vnd.github+json',
    'X-GitHub-Api-Version': '2022-11-28',
  };
}

function requireGitHubCredentials(): { clientId: string; clientSecret: string } {
  const clientId = process.env.GITHUB_CLIENT_ID;
  const clientSecret = process.env.GITHUB_CLIENT_SECRET;

  if (!clientId || !clientSecret) {
    throw new Error('GitHub OAuth not configured: GITHUB_CLIENT_ID and GITHUB_CLIENT_SECRET must be set');
  }

  return { clientId, clientSecret };
}

function signAccessToken(payload: object, expiresIn: SignOptions['expiresIn'] = '7d'): string {
  return jwt.sign(payload, config.jwt.secret, { expiresIn });
}

function signRefreshToken(payload: object, expiresIn: SignOptions['expiresIn'] = '30d'): string {
  return jwt.sign(payload, config.jwt.refreshSecret, { expiresIn });
}

