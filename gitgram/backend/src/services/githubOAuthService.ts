/**
 * Builds the GitHub OAuth authorization URL.
 *
 * Requested scopes:
 *   - user       — read the user's public and private profile data
 *   - public_repo — read/write access to public repositories (needed for social features)
 *   - read:org   — read organization membership (for org-backed accounts)
 *
 * @param state - CSRF protection token generated by the caller
 */
export function getAuthorizationUrl(state: string): string {
  const { clientId } = requireGitHubCredentials();
  const redirectUri = process.env.GITHUB_REDIRECT_URI;
  const scopes = ['user', 'public_repo', 'read:org'].join(' ');

  const params = new URLSearchParams({
    client_id: clientId,
    scope: scopes,
    state,
    ...(redirectUri ? { redirect_uri: redirectUri } : {}),
  });

  return `https://github.com/login/oauth/authorize?${params.toString()}`;
}

/**
 * Exchanges a GitHub authorization code for an access token.
 *
 * @param code  - The one-time authorization code from GitHub's callback
 * @param state - The state value returned in the callback (callers should verify
 *                it matches the value sent to `getAuthorizationUrl` before calling here)
 */
export async function exchangeCode(code: string, state: string): Promise<GitHubTokens> {
  const { clientId, clientSecret } = requireGitHubCredentials();
  const redirectUri = process.env.GITHUB_REDIRECT_URI;

  logger.info(`Exchanging GitHub OAuth code (state=${state.slice(0, 8)}...)`);

  const response = await axios.post<GitHubTokens>(
    'https://github.com/login/oauth/access_token',
    {
      client_id: clientId,
      client_secret: clientSecret,
      code,
      ...(redirectUri ? { redirect_uri: redirectUri } : {}),
    },
    {
      headers: {
        Accept: 'application/json',
        'Content-Type': 'application/json',
      },
    }
  );

  const data = response.data as unknown as Record<string, unknown>;

  if (data['error']) {
    const description = String(data['error_description'] ?? data['error']);
    logger.error('GitHub token exchange error:', data);
    throw new Error(`GitHub token exchange failed: ${description}`);
  }

  if (!data['access_token']) {
    throw new Error('GitHub returned no access token');
  }

  return {
    access_token: String(data['access_token']),
    token_type: String(data['token_type'] ?? 'bearer'),
    scope: String(data['scope'] ?? ''),
  };
}

/**
 * Fetches the authenticated user's public GitHub profile.
 *
 * @param accessToken - A valid GitHub OAuth access token
 */
export async function getGitHubUser(accessToken: string): Promise<GitHubUser> {
  const response = await axios.get<GitHubUser>('https://api.github.com/user', {
    headers: githubApiHeaders(accessToken),
  });

  assertRateLimitNotExhausted(response, 'GET /user');

  return response.data;
}

/**
 * Fetches all email addresses associated with the authenticated GitHub account.
 *
 * Useful when `GitHubUser.email` is null because the user has hidden their
 * primary email on their public profile.
 *
 * @param accessToken - A valid GitHub OAuth access token (must include `user` scope)
 */
export async function getGitHubEmails(accessToken: string): Promise<GitHubEmail[]> {
  const response = await axios.get<GitHubEmail[]>('https://api.github.com/user/emails', {
    headers: githubApiHeaders(accessToken),
  });

  assertRateLimitNotExhausted(response, 'GET /user/emails');

  return response.data;
}

/**
 * Resolves the primary verified email for a GitHub user.
 *
 * Falls back to the emails endpoint when the profile email is hidden.
 * Throws if no verified primary email can be found.
 *
 * @param user        - The GitHub user profile
 * @param accessToken - A valid GitHub OAuth access token
 */
async function resolvePrimaryEmail(user: GitHubUser, accessToken: string): Promise<string> {
  if (user.email) {
    return user.email;
  }

  logger.info(`GitHub user ${user.login} has hidden email — querying /user/emails`);

  const emails = await getGitHubEmails(accessToken);
  const primary = emails.find((e) => e.primary && e.verified);

  if (primary) {
    return primary.email;
  }

  const anyVerified = emails.find((e) => e.verified);
  if (anyVerified) {
    logger.warn(`No primary verified email for ${user.login}, using first verified: ${anyVerified.email}`);
    return anyVerified.email;
  }

  throw new Error(
    'No verified email address found on GitHub. ' +
      'Please verify at least one email address on your GitHub account and try again.'
  );
}

/**
 * Refreshes stored profile data for an existing user from the GitHub API.
 *
 * Updates: avatar, bio, display name, location, website, follower/following counts.
 * Silently logs and returns if the stored token is missing or the API call fails.
 *
 * @param userId - Internal Gitgram user ID
 */
export async function refreshUserGitHubData(userId: string): Promise<void> {
  const user = await prisma.user.findUnique({
    where: { id: userId },
    select: { id: true, githubAccessToken: true, githubUsername: true },
  });

  if (!user?.githubAccessToken) {
    logger.warn(`refreshUserGitHubData: no stored GitHub token for user ${userId}`);
    return;
  }

  let profile: GitHubUser;

  try {
    profile = await getGitHubUser(user.githubAccessToken);
  } catch (err: unknown) {
    logger.error(`refreshUserGitHubData: GitHub API call failed for user ${userId}`, err);
    return;
  }

  await prisma.user.update({
    where: { id: userId },
    data: {
      avatar: profile.avatar_url,
      bio: profile.bio ?? undefined,
      displayName: profile.name ?? undefined,
      githubUsername: profile.login,
    },
  });

  logger.info(`Refreshed GitHub profile data for user ${userId} (@${profile.login})`);
}

/**
 * Handles the complete GitHub OAuth callback flow:
 *
 * 1. Exchange the authorization code for tokens
 * 2. Fetch the GitHub user profile
 * 3. Resolve the primary email
 * 4. Find an existing Gitgram user by GitHub ID or email (link / create as needed)
 * 5. Issue Gitgram JWT access + refresh tokens
 * 6. Persist a new session
 *
 * @param code  - Authorization code from GitHub's callback
 * @param state - State value (caller is responsible for CSRF validation before invoking)
 */
export async function handleCallback(code: string, state: string): Promise<CallbackResult> {
  // Step 1 — Exchange code
  const githubTokens = await exchangeCode(code, state);

  // Step 2 — Fetch profile
  const githubUser = await getGitHubUser(githubTokens.access_token);

  // Step 3 — Resolve email
  const resolvedEmail = await resolvePrimaryEmail(githubUser, githubTokens.access_token);

  // Step 4 — Upsert Gitgram user
  const { dbUser, isNewUser } = await upsertUser(githubUser, githubTokens.access_token, resolvedEmail);

  // Step 5 — Generate JWTs
  const tokens = issueTokens(dbUser.id);

  // Step 6 — Persist session
  await prisma.session.create({
    data: {
      userId: dbUser.id,
      refreshToken: tokens.refreshToken,
      expiresAt: new Date(Date.now() + 30 * 24 * 60 * 60 * 1000),
    },
  });

  logger.info(`GitHub OAuth callback completed for user ${dbUser.id} (${isNewUser ? 'new' : 'existing'})`);

  return {
    user: {
      id: dbUser.id,
      email: dbUser.email,
      username: dbUser.username,
      displayName: dbUser.displayName,
      avatar: dbUser.avatar,
      githubUsername: dbUser.githubUsername,
      bio: dbUser.bio,
    },
    isNewUser,
    tokens,
  };
}

